import {
  boolean,
  char,
  doublePrecision,
  integer,
  pgTable,
  real,
  timestamp,
  uuid,
  varchar,
} from 'drizzle-orm/pg-core';
import { drivers } from './drivers';
import { users } from './users';

export const trips = pgTable('trips', {
  id: uuid('id').defaultRandom().primaryKey(),
  passenger_id: uuid('passenger_id').references(() => users.id, { onDelete: 'set null' }),
  driver_id: uuid('driver_id').references(() => drivers.id),
  status: varchar('status', { length: 30 }).notNull().default('request_received'),
  origin_lat: real('origin_lat').notNull(),
  origin_lng: real('origin_lng').notNull(),
  dest_lat: real('dest_lat').notNull(),
  dest_lng: real('dest_lng').notNull(),
  origin_address: varchar('origin_address', { length: 512 }),
  dest_address: varchar('dest_address', { length: 512 }),
  pickup_instructions: varchar('pickup_instructions', { length: 256 }),
  distance_km: real('distance_km'),
  duration_minutes: real('duration_minutes'),
  base_fare: doublePrecision('base_fare'),
  distance_fare: doublePrecision('distance_fare'),
  time_fare: doublePrecision('time_fare'),
  total_fare: doublePrecision('total_fare').notNull(),
  platform_fee: doublePrecision('platform_fee').notNull(),
  driver_earnings: doublePrecision('driver_earnings').notNull(),
  tip_amount: doublePrecision('tip_amount').default(0),
  payment_method: varchar('payment_method', { length: 30 }).default('cash'),
  /** Passenger-requested class: `auto` | `moto` (canonical). */
  vehicle_type: varchar('vehicle_type', { length: 20 }).notNull().default('auto'),
  is_collected: boolean('is_collected').default(false).notNull(),
  tolerance_minutes: integer('tolerance_minutes').default(5),
  waiting_since: timestamp('waiting_since'),
  assigned_at: timestamp('assigned_at'),
  verification_code: char('verification_code', { length: 4 }),
  expires_at: timestamp('expires_at'),
  completed_lat: real('completed_lat'),
  completed_lng: real('completed_lng'),
  completed_distance_m: real('completed_distance_m'),
  completed_gps_accuracy_m: real('completed_gps_accuracy_m'),
  completed_at: timestamp('completed_at', { withTimezone: true }),
  completion_type: varchar('completion_type', { length: 30 }),
  completion_exception_reason: varchar('completion_exception_reason', { length: 64 }),
  completion_exception_note: varchar('completion_exception_note', { length: 200 }),
  created_at: timestamp('created_at').defaultNow().notNull(),
  updated_at: timestamp('updated_at').defaultNow().notNull(),
});
